-- Cole tudo isto no SQL Editor do Supabase e clique em "Run".
-- Cria a tabela de favoritos e libera leitura, inserção e exclusão para o site.

create table public.favoritos (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now(),
  nome_item text not null unique,
  dados_extra text
);

-- Liga a segurança por linha (RLS)
alter table public.favoritos enable row level security;

-- Políticas abertas para o papel "anon" (o visitante do site)
create policy "Todos podem ler"    on public.favoritos for select to anon using (true);
create policy "Todos podem salvar" on public.favoritos for insert to anon with check (true);
create policy "Todos podem excluir" on public.favoritos for delete to anon using (true);

-- Garante a permissão de acesso à tabela
grant select, insert, delete on public.favoritos to anon;
